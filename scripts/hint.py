#!/usr/bin/env python3
"""Hint Noto Serif Mono TTFs with ttfautohint and apply the 2.5 hinting fixes.

Run after `gftools builder` (which is configured with autohintTTF: false):

    python3 scripts/hint.py fonts/ttf/NotoSerifMono-*.ttf

Steps, in place for each font:
  1. ttfautohint with the settings Noto Serif Mono has always used
     (hinting range 7-72 ppem, limit 220, no x-height increase,
     Windows compatibility, natural stem widths in every renderer),
     plus the style's control file from sources/hinting/ (generated by
     scripts/make_hint_controls.py: unsegmented U+210A and U+25CC, and
     delta hints that keep accents clear of their letters).
  2. Set head.flags bit 3 (integer ppem), as the OpenType spec
     recommends for hinted fonts.
  3. Family alignment: ttfautohint measures each face separately, and
     Bold's x-height overshoot comes out a few units different from
     the other faces. Because the hints scale every glyph to fit the
     rounded x-height, that made Bold one pixel taller or shorter than
     Regular at many sizes. This step copies the Regular values into the
     x-height alignment CVT entries of the other faces. It finds those
     entries by parsing the prep program (the LOOPCALL to fpgm function 0,
     bci_align_x_height), so it keeps working when ttfautohint renumbers
     the CVT.
  4. Remove instructions from glyphs whose programs fail in FreeType's
     pedantic mode (found with scripts/qa/pedantic.sh): U+1ABF, U+1AC0.
  5. Add a STAT table (wght + ital axes). gftools builder only writes
     STAT for variable fonts, and Google Fonts requires it on statics.
  6. Add a meta table declaring the design and supported scripts
     (dlng/slng: Latn, Grek, Cyrl), as Google Fonts recommends.
  7. Rewrite fonts/webfonts/*.woff2 from the finished TTFs. gftools builder
     compresses the webfonts before this script runs, so without this step
     they would ship without hinting or STAT.
"""
import sys, os, shutil, tempfile
from fontTools.ttLib import TTFont
from fontTools.ttLib.tables import ttProgram

TTFA = dict(hinting_range_min=7, hinting_range_max=72, hinting_limit=220,
            increase_x_height=0, windows_compatibility=True, no_info=True)
BROKEN_PROGRAMS = ['uni1ABF', 'uni1AC0']
SCRIPTS = 'Latn, Grek, Cyrl'


def control_file(path):
    """sources/hinting/<font name>.ttfa.txt, written by scripts/make_hint_controls.py."""
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    f = os.path.join(root, 'sources', 'hinting', os.path.splitext(os.path.basename(path))[0] + '.ttfa.txt')
    return f if os.path.exists(f) else None


def autohint(path, out=None, control=None):
    """Hint path into out (default: in place). control: control-file text; by default
    the style's checked-in control file, if any."""
    from ttfautohint import ttfautohint
    from ttfautohint.options import StemWidthMode
    if control is None:
        cf = control_file(path)
        control = open(cf, encoding='utf-8').read() if cf else ''
    tmp = tempfile.NamedTemporaryFile(suffix='.ttf', delete=False).name
    extra = {'control_buffer': control.encode()} if control.strip() else {}
    ttfautohint(in_file=path, out_file=tmp,
                gray_stem_width_mode=StemWidthMode.NATURAL,
                gdi_cleartype_stem_width_mode=StemWidthMode.NATURAL,
                dw_cleartype_stem_width_mode=StemWidthMode.NATURAL, **TTFA, **extra)
    shutil.move(tmp, out or path)


def xheight_cvt_indices(font):
    """CVT indices passed to bci_align_x_height (fpgm function 0) by prep."""
    asm = [x.split('\t')[0].strip() for x in font['prep'].program.getAssembly()]
    for i, tok in enumerate(asm):
        if tok == 'LOOPCALL[ ]' and asm[i - 1] == '0':
            count = int(asm[i - 2])
            # values were pushed before "count 0": walk back over the numeric tokens
            vals = []
            j = i - 3
            while len(vals) < count and j >= 0:
                if asm[j].lstrip('-').isdigit():
                    vals.append(int(asm[j]))
                j -= 1
            return [v for v in vals if v > 0]
    raise RuntimeError('bci_align_x_height LOOPCALL not found in prep')


def align_xheight_cvt(t, ref, name=''):
    """Copy ref's x-height alignment CVT values into t (step 3). Returns {index: (old, new)}."""
    idx = xheight_cvt_indices(t)
    if idx != xheight_cvt_indices(ref):
        raise RuntimeError(f'{name}: CVT layout differs from Regular; cannot align')
    cv, rv = t['cvt '].values, ref['cvt '].values
    changed = {i: (int(cv[i]), int(rv[i])) for i in idx if cv[i] != rv[i]}
    for i in changed: cv[i] = rv[i]
    return changed


def add_stat(font):
    from fontTools.otlLib.builder import buildStatTable
    weight = font['OS/2'].usWeightClass
    italic = bool(font['OS/2'].fsSelection & 1)
    axes = [
        dict(tag='wght', name='Weight', values=[
            dict(value=weight, name='Bold' if weight == 700 else 'Regular',
                 flags=0 if weight == 700 else 2,
                 **({} if weight == 700 else {'linkedValue': 700}))]),
        dict(tag='ital', name='Italic', values=[
            dict(value=1, name='Italic') if italic else
            dict(value=0, name='Roman', flags=2, linkedValue=1)]),
    ]
    buildStatTable(font, axes, elidedFallbackName=2)


def add_meta(font):
    from fontTools.ttLib import newTable
    meta = font['meta'] if 'meta' in font else newTable('meta')
    meta.data['dlng'] = SCRIPTS
    meta.data['slng'] = SCRIPTS
    font['meta'] = meta


def postfix(paths):
    fonts = {p: TTFont(p) for p in paths}
    ref = next((t for p, t in fonts.items() if p.endswith('-Regular.ttf')), None)
    for p, t in fonts.items():
        log = []
        t['head'].flags |= 1 << 3
        log.append('integer ppem')
        for n in BROKEN_PROGRAMS:
            g = t['glyf'].glyphs.get(n) and t['glyf'][n]
            if g is not None and hasattr(g, 'program'):
                prog = ttProgram.Program(); prog.fromBytecode(b''); g.program = prog
        log.append('removed failing glyph programs')
        add_stat(t)
        log.append('STAT added')
        add_meta(t)
        log.append('meta added')
        if ref is not None and t is not ref:
            changed = align_xheight_cvt(t, ref, p)
            log.append(f'x-height CVT aligned to Regular {changed}' if changed else 'x-height CVT already aligned')
        t.save(p)
        woff2 = write_webfont(p)
        if woff2:
            log.append('rewrote ' + os.path.relpath(woff2))
        print(os.path.basename(p) + ': ' + '; '.join(log))


def write_webfont(path):
    """Write <outputDir>/webfonts/<name>.woff2 next to <outputDir>/ttf/<name>.ttf, if that dir exists."""
    webdir = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(path))), 'webfonts')
    if not os.path.isdir(webdir):
        return None
    out = os.path.join(webdir, os.path.splitext(os.path.basename(path))[0] + '.woff2')
    t = TTFont(path)
    t.flavor = 'woff2'
    t.save(out)
    return out


if __name__ == '__main__':
    paths = sys.argv[1:]
    if '--no-autohint' in paths:
        paths.remove('--no-autohint')
    else:
        for p in paths:
            autohint(p)
    postfix(paths)
